from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from tesis_domain_extensions.catalog import SUPPORTED_DOMAINS  # noqa: E402

REQUIRED_FIELDS = {"schema_version", "domain_id", "domain_version", "entry"}
FIRST_PARTY_UI_DOMAINS = {
    ("single-row-facility-layout", "1.0.0"),
    ("single-row-facility-layout", "2.0.0"),
    ("single-row-facility-layout", "2.1.0"),
}


def _load_record(manifest_path: Path, root: Path) -> tuple[str, str, str]:
    document = json.loads(manifest_path.read_text(encoding="utf-8"))
    if not isinstance(document, dict) or set(document) != REQUIRED_FIELDS:
        raise ValueError(f"invalid fields in {manifest_path}")
    if document["schema_version"] != "1.0.0":
        raise ValueError(f"unsupported manifest schema in {manifest_path}")
    domain_id = document["domain_id"]
    version = document["domain_version"]
    entry = document["entry"]
    if not all(isinstance(value, str) for value in (domain_id, version, entry)):
        raise ValueError(f"manifest values must be strings in {manifest_path}")
    if (domain_id, version) not in SUPPORTED_DOMAINS:
        raise ValueError(f"domain {domain_id}@{version} is not in SUPPORTED_DOMAINS")
    ui_root = manifest_path.parent.resolve(strict=True)
    entry_path = (ui_root / entry).resolve(strict=True)
    entry_path.relative_to(ui_root)
    if not entry_path.is_file():
        raise ValueError(f"UI entry is not a file: {entry_path}")
    target = root / "desktop" / "src" / "generated" / "domain-registry.ts"
    relative = os.path.relpath(entry_path, target.parent).replace("\\", "/")
    if Path(relative).suffix in {".ts", ".tsx"}:
        relative = relative[: -len(Path(relative).suffix)]
    if not relative.startswith("."):
        relative = f"./{relative}"
    return domain_id, version, relative


def generate_registry(root: Path = ROOT) -> str:
    manifests = sorted(
        (root / "src" / "tesis_domain_extensions" / "domains").glob("*/ui/domain-ui*.json")
    )
    records: list[tuple[str, str, str]] = []
    identities: set[tuple[str, str]] = set()
    for manifest_path in manifests:
        domain_id, version, relative = _load_record(manifest_path, root)
        identity = (domain_id, version)
        if identity in identities:
            raise ValueError(f"duplicate domain UI {domain_id}@{version}")
        identities.add(identity)
        records.append((domain_id, version, relative))

    missing = FIRST_PARTY_UI_DOMAINS - identities
    if missing:
        rendered = ", ".join(f"{domain_id}@{version}" for domain_id, version in sorted(missing))
        raise ValueError(f"missing first-party domain UI: {rendered}")

    lines = [
        "/* Generated by scripts/generate_desktop_registry.py. Do not edit. */",
        'import type { DomainUiModule } from "@domain-ui-sdk";',
        "",
        "export const domainUiRegistry = {",
    ]
    for domain_id, version, entry in records:
        key = f"{domain_id}@{version}"
        lines.extend(
            [
                f'  "{key}": () =>',
                f'    import("{entry}") as Promise<DomainUiModule>,',
            ]
        )
    lines.extend(["} as const;", ""])
    return "\n".join(lines)


def main() -> None:
    target = ROOT / "desktop" / "src" / "generated" / "domain-registry.ts"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(generate_registry(), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
